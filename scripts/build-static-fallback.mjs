#!/usr/bin/env node
/**
 * Builds the portable fallback: the production site as plain static files that any static host Highland controls
 * can serve (Netlify, Cloudflare Pages, Vercel, S3/CloudFront…), independent of the main Vercel project.
 *
 *   node scripts/build-static-fallback.mjs            → fallback/highland-static-<commit>/ + .tar.gz
 *
 * Same pages, URLs, canonicals, structured data, tracking and campaign pages as production. Differences, by design:
 * - There is no server, so lead forms cannot deliver: they show their existing error state with the phone number and
 *   sales email (never a false "sent"). Restore the main deployment as soon as possible.
 * - Redirects and 410s come from host config written next to the files: `_redirects` + `_headers` (Netlify and
 *   Cloudflare Pages; Cloudflare serves the two 410 paths as 404) and `vercel.json` (redirects; 410 paths as 404).
 */
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const sha = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: root }).toString().trim();
const stash = path.join(root, ".fallback-stash");
const moved = [
  ["app/api", "api"],
  ["proxy.ts", "proxy.ts"],
];
rmSync(stash, { recursive: true, force: true });
mkdirSync(stash);
for (const [from, to] of moved) if (existsSync(path.join(root, from))) renameSync(path.join(root, from), path.join(stash, to));
try {
  execFileSync("npx", ["next", "build"], {
    cwd: root,
    stdio: "inherit",
    env: { ...process.env, STATIC_EXPORT: "1", SITE_INDEXING: "on", NEXT_PUBLIC_SITE_URL: process.env.NEXT_PUBLIC_SITE_URL ?? "https://highlandcabinetry.com" },
  });
} finally {
  for (const [from, to] of moved) if (existsSync(path.join(stash, to))) renameSync(path.join(stash, to), path.join(root, from));
  rmSync(stash, { recursive: true, force: true });
}

const { redirects } = await import(path.join(root, "content/redirects.ts")).catch(async () => {
  // Plain Node cannot import .ts: read the generated JSON literal instead.
  const src = (await import("node:fs")).readFileSync(path.join(root, "content/redirects.ts"), "utf8");
  return { redirects: JSON.parse(src.slice(src.indexOf("= [") + 2, src.lastIndexOf("]") + 1)) };
});
const goneSrc = (await import("node:fs")).readFileSync(path.join(root, "content/gone.ts"), "utf8");
const gone = JSON.parse(goneSrc.slice(goneSrc.indexOf("= [") + 2, goneSrc.lastIndexOf("]") + 1));

const name = `highland-static-${sha}`;
const dir = path.join(root, "fallback", name);
rmSync(dir, { recursive: true, force: true });
mkdirSync(path.dirname(dir), { recursive: true });
// With a custom distDir, `output: "export"` writes the exported site into that directory.
cpSync(path.join(root, ".next-static"), dir, { recursive: true });
rmSync(path.join(root, ".next-static"), { recursive: true, force: true });

writeFileSync(
  path.join(dir, "gone.html"),
  '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="robots" content="noindex"><title>Page removed — Highland Cabinetry</title></head><body style="font-family:system-ui;padding:3rem;max-width:40rem;margin:auto"><h1>This page has been removed.</h1><p><a href="/">Go to the Highland Cabinetry homepage</a></p></body></html>',
);
const variants = (s) => (s.endsWith("/") && s.length > 1 ? [s, s.slice(0, -1)] : [s]);
const lines = [
  "# Generated by scripts/build-static-fallback.mjs — permanent redirects (query strings pass through), then 410s.",
  ...redirects.flatMap((r) => variants(r.source).map((s) => `${s}  ${r.destination}  308`)),
  ...gone.flatMap((g) => [`${g}  /gone.html  410`, `${g.replace(/\/?$/, "/")}*  /gone.html  410`]),
];
writeFileSync(path.join(dir, "_redirects"), lines.join("\n") + "\n");
writeFileSync(
  path.join(dir, "_headers"),
  "/*\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: strict-origin-when-cross-origin\n  X-Frame-Options: SAMEORIGIN\n/media/*\n  Cache-Control: public, max-age=31536000, immutable\n",
);
writeFileSync(
  path.join(dir, "vercel.json"),
  JSON.stringify({ trailingSlash: true, redirects: redirects.map((r) => ({ source: r.source, destination: r.destination, permanent: true })) }, null, 2),
);
writeFileSync(
  path.join(dir, "FALLBACK-README.txt"),
  `Highland Cabinetry — static fallback built from commit ${sha} on ${new Date().toISOString()}.\n` +
    "Upload this folder as the site root to a static host Highland controls, then point DNS at it (docs/launch/CUTOVER.md, Rollback).\n" +
    "Lead forms cannot deliver from a static host; they show the phone number and sales email instead.\n",
);
execFileSync("tar", ["-czf", `${name}.tar.gz`, name], { cwd: path.dirname(dir) });
console.log(`\nFallback ready: fallback/${name}/ and fallback/${name}.tar.gz`);
